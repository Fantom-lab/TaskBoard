
/*
 * TaskBoard — middleware проверки авторизации.
 *
 * Файл отвечает за:
 * 1. Проверку наличия пользовательской сессии.
 * 2. Проверку идентификатора пользователя в сессии.
 * 3. Перенаправление неавторизованных посетителей на страницу входа.
 * 4. Передачу управления следующему обработчику для авторизованных пользователей.
 *
 * Middleware используется для защиты страниц и маршрутов,
 * доступных только после входа в аккаунт.
 */

// Проверяем, авторизован ли пользователь.
function requireAuth(req, res, next) {
    // Сессия создаётся middleware из middleware/session.js.
    // Если сессии или идентификатора пользователя нет,
    // пользователь не считается авторизованным.
    if (!req.session || !req.session.userId) {
        return res.redirect("/auth.html");
    }

    // Пользователь авторизован — продолжаем обработку запроса.
    return next();
}

// Экспортируем middleware для использования в server.js
// и маршрутах, требующих авторизации.
module.exports = requireAuth;
