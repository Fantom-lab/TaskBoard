
/*
 * TaskBoard — главный файл сервера.
 *
 * Здесь настраиваются:
 * 1. Подключение библиотек и маршрутов.
 * 2. Обработка данных из запросов.
 * 3. Пользовательские сессии.
 * 4. API регистрации, авторизации и задач.
 * 5. Защита главной страницы.
 * 6. Раздача HTML, CSS и JavaScript.
 * 7. Запуск сервера.
 */

// Загружаем переменные окружения из файла .env.
require("dotenv").config();

const express = require("express");
const path = require("path");

// Подключаем middleware для сессий и проверки авторизации.
const sessionMiddleware = require("./middleware/session");
const requireAuth = require("./middleware/requireAuth");

// Подключаем маршруты API.
const authRoutes = require("./routes/auth");
const taskRoutes = require("./routes/tasks");

// Создаём приложение Express.
const app = express();

// Порт, на котором работает TaskBoard.
const PORT = process.env.PORT || 3000;

// --------------------------------------------------
// 1. Обработка входящих запросов
// --------------------------------------------------

// Разбираем данные HTML-форм.
app.use(express.urlencoded({ extended: false }));

// Разбираем JSON, который отправляет frontend.
app.use(express.json({ limit: "100kb" }));

// Подключаем пользовательские сессии.
app.use(sessionMiddleware);

// --------------------------------------------------
// 2. API: авторизация и задачи
// --------------------------------------------------

// Регистрация, вход, выход и настройки пользователя.
app.use("/api/auth", authRoutes);

// Создание, получение, изменение и удаление задач.
app.use("/api/tasks", taskRoutes);

// --------------------------------------------------
// 3. Защита главной страницы
// --------------------------------------------------

// Если пользователь открывает index.html напрямую,
// перенаправляем его на авторизацию, если он не вошёл.
app.get("/index.html", (req, res, next) => {
    if (!req.session || !req.session.userId) {
        return res.redirect("/auth.html");
    }

    next();
});

// Главная страница доступна только авторизованным пользователям.
app.get("/", requireAuth, (req, res) => {
    res.sendFile(path.join(__dirname, "public", "index.html"));
});

// --------------------------------------------------
// 4. Статические файлы frontend
// --------------------------------------------------

// Раздаём CSS, JavaScript, изображения и auth.html.
// Автоматическую выдачу index.html отключаем,
// поскольку доступ к главной странице защищён.
app.use(express.static(path.join(__dirname, "public"), {
    index: false
}));

// --------------------------------------------------
// 5. Проверка состояния сервера
// --------------------------------------------------

// Используется для проверки доступности сервера.
app.get("/api/status", (req, res) => {
    res.json({
        success: true,
        message: "Сервер TaskBoard работает"
    });
});

// --------------------------------------------------
// 6. Обработка неизвестных API-маршрутов
// --------------------------------------------------

// Возвращаем понятный ответ, если API-маршрут не найден.
app.use("/api", (req, res) => {
    res.status(404).json({
        success: false,
        message: "API-маршрут не найден"
    });
});

// --------------------------------------------------
// 7. Обработка ошибок Express
// --------------------------------------------------

// Последний обработчик ловит ошибки middleware и маршрутов,
// переданные через next(error).
app.use((err, req, res, next) => {
    console.error("Ошибка сервера:", err);

    if (res.headersSent) {
        return next(err);
    }

    res.status(500).json({
        success: false,
        message: "Внутренняя ошибка сервера"
    });
});

// --------------------------------------------------
// 8. Запуск сервера
// --------------------------------------------------

app.listen(PORT, () => {
    console.log(`TaskBoard запущен: http://localhost:${PORT}`);
});
