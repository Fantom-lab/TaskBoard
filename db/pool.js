
/*
 * TaskBoard — подключение к PostgreSQL.
 *
 * Файл отвечает за:
 * 1. Создание общего пула подключений к базе данных.
 * 2. Чтение параметров подключения из переменных окружения.
 * 3. Обработку ошибок неактивных соединений.
 * 4. Проверку доступности базы данных.
 * 5. Экспорт пула и функции проверки для других модулей.
 */

const { Pool } = require("pg");

// =========================================================
// 1. Проверка настроек окружения
// =========================================================

// В production пароль должен быть задан явно.
// В локальной разработке допускается пустой пароль,
// если это соответствует настройкам PostgreSQL.
if (
    process.env.NODE_ENV === "production" &&
    !process.env.DB_PASSWORD
) {
    throw new Error(
        "Для production необходимо задать переменную DB_PASSWORD."
    );
}

// =========================================================
// 2. Создание пула подключений
// =========================================================

// Параметры подключения читаются из .env.
// Значения по умолчанию предназначены для локальной разработки.
const pool = new Pool({
    host: process.env.DB_HOST || "localhost",
    port: Number(process.env.DB_PORT) || 5432,
    database: process.env.DB_NAME || "taskboard",
    user: process.env.DB_USER || "postgres",
    password: process.env.DB_PASSWORD,

    // Максимальное количество одновременных соединений.
    max: 10,

    // Время ожидания свободного соединения.
    connectionTimeoutMillis: 5000,

    // Закрытие простаивающих соединений через 30 секунд.
    idleTimeoutMillis: 30000,

    // Максимальное время выполнения SQL-запроса.
    statement_timeout: 10000
});

// =========================================================
// 3. Обработка ошибок пула
// =========================================================

// Обрабатываем ошибки соединений, которые простаивают в пуле.
// Это предотвращает необработанные ошибки на уровне процесса.
pool.on("error", (error) => {
    console.error(
        "Ошибка неактивного подключения PostgreSQL:",
        error.message
    );
});

// =========================================================
// 4. Проверка подключения к базе данных
// =========================================================

// Выполняет короткий запрос и возвращает время сервера БД.
// При ошибке исключение передаётся вызывающему коду.
// Благодаря этому сервер может корректно отреагировать
// на недоступность базы данных при запуске.
async function checkDatabaseConnection() {
    const result = await pool.query(
        "SELECT NOW() AS server_time"
    );

    return result.rows[0].server_time;
}

// =========================================================
// 5. Экспорт пула и функции проверки
// =========================================================

// В маршрутах используй:
// const { pool } = require("../db/pool");
//
// Для проверки подключения при запуске:
// const { checkDatabaseConnection } = require("./db/pool");
module.exports = {
    pool,
    checkDatabaseConnection
};
